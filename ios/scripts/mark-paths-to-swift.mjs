// Generates the iOS copy of every Trifecta Sheet's hand-drawn mark paths
// from the web client's own extracted data.
//
// Run from the repo root:
//   node ios/scripts/mark-paths-to-swift.mjs
//
// ## Why generated rather than transcribed
//
// There are 122 paths across six Sheets, each a few hundred characters of
// cubic beziers. Hand-copying them is a hundred chances to drop a digit,
// and a dropped digit in path data does not fail -- it draws a slightly
// wrong mark that nobody notices.
//
// ## Why from the TypeScript rather than from the SVGs
//
// web/scripts/extract-mark-paths.mjs already reads Joshua's SVG exports,
// resolves each named <g> to a target index, works out the viewBox against
// the embedded scene placement, and measures every stroke's length. All of
// that has been verified Sheet by Sheet against real play. Re-deriving it
// here would be a second implementation of the hard part; reading its
// output is one source of truth with one extra format.
//
// Re-run this after the web extractor runs again.
import { readFileSync, writeFileSync } from 'node:fs';

const SHEETS = [
  ['nightmare', 'nightmareMarkPaths.ts', 'NIGHTMARE_MARK_ART'],
  ['demonking', 'demonKingMarkPaths.ts', 'DEMON_KING_MARK_ART'],
  ['kinghuman', 'kingHumanMarkPaths.ts', 'KING_HUMAN_MARK_ART'],
  ['ambush', 'ambushMarkPaths.ts', 'AMBUSH_MARK_ART'],
  ['bombsquad', 'bombSquadMarkPaths.ts', 'BOMB_SQUAD_MARK_ART'],
  ['tentaclepit', 'tentaclePitMarkPaths.ts', 'TENTACLE_PIT_MARK_ART'],
];

/** The generated TS is machine-written and regular, so it is read with
 * targeted expressions rather than parsed as a module -- importing it
 * would mean resolving its own type imports from a different workspace. */
function parseSheet(source) {
  const viewBox = source.match(
    /viewBox:\s*\{\s*minX:\s*(-?[\d.]+),\s*minY:\s*(-?[\d.]+),\s*width:\s*(-?[\d.]+),\s*height:\s*(-?[\d.]+)\s*\}/,
  );
  if (!viewBox) throw new Error('no viewBox');
  const strokeWidth = source.match(/strokeWidth:\s*(-?[\d.]+)/);
  if (!strokeWidth) throw new Error('no strokeWidth');

  const sides = {};
  for (const side of ['humans', 'demons']) {
    // Each side is a list of targets; each target a list of strokes.
    const block = source.match(new RegExp(`${side}:\\s*\\[([\\s\\S]*?)\\n  \\]`));
    if (!block) throw new Error(`no ${side} block`);

    const targets = [];
    // Targets are separated by a comment line naming the index, which the
    // extractor always writes.
    const chunks = block[1].split(/\n\s*\/\/ \d+ -- /).slice(1);
    for (const chunk of chunks) {
      const strokes = [...chunk.matchAll(/\{\s*length:\s*(-?[\d.]+),\s*d:\s*'([^']*)'\s*\}/g)].map(
        (m) => ({ length: Number(m[1]), d: m[2] }),
      );
      targets.push(strokes);
    }
    sides[side] = targets;
  }

  return {
    viewBox: viewBox.slice(1, 5).map(Number),
    strokeWidth: Number(strokeWidth[1]),
    sides,
  };
}

function swiftFor(style, art) {
  const side = (name) =>
    art.sides[name]
      .map(
        (strokes, i) =>
          `            // ${i}\n            [\n` +
          strokes
            .map((s) => `                MarkStroke(length: ${s.length}, d: "${s.d}"),`)
            .join('\n') +
          `\n            ],`,
      )
      .join('\n');

  const [minX, minY, width, height] = art.viewBox;
  return `    static let ${style} = DrawnMarkSet(
        viewBox: MarkViewBox(minX: ${minX}, minY: ${minY}, width: ${width}, height: ${height}),
        strokeWidth: ${art.strokeWidth},
        humans: [
${side('humans')}
        ],
        demons: [
${side('demons')}
        ]
    )`;
}

const bodies = [];
for (const [style, file] of SHEETS) {
  const art = parseSheet(readFileSync(`web/src/lib/${file}`, 'utf8'));
  const counts = ['humans', 'demons'].map((s) => art.sides[s].length);
  if (counts.some((n) => n !== 9)) {
    // Nine targets a side is the Family's own rule -- losing all nine
    // loses the Night -- so a count that is not nine means the extraction
    // or this reader is wrong, and silently shipping it would draw marks
    // on the wrong targets.
    throw new Error(`${style}: expected 9 targets a side, got ${counts.join('/')}`);
  }
  bodies.push(swiftFor(style, art));
  console.log(`${style}: ${counts.join('/')} targets, ${art.sides.humans.flat().length + art.sides.demons.flat().length} strokes`);
}

const out = `// GENERATED by ios/scripts/mark-paths-to-swift.mjs -- do not edit by hand.
// Source: web/src/lib/*MarkPaths.ts, themselves generated from Joshua's
// own SVG exports by web/scripts/extract-mark-paths.mjs. Re-run both
// after any re-export.
import Foundation

enum TrifectaMarkArt {
    static func forStyle(_ style: String) -> DrawnMarkSet? { all[style] }

    static let all: [String: DrawnMarkSet] = [
${SHEETS.map(([style]) => `        "${style}": ${style},`).join('\n')}
    ]

${bodies.join('\n\n')}
}
`;

writeFileSync('ios/Shared/TrifectaMarkArt.swift', out);
console.log(`\nwrote ios/Shared/TrifectaMarkArt.swift (${(out.length / 1024).toFixed(0)} KB)`);
